PLACES = ["旧码头", "城南河滩", "档案室", "会客室门口", "旧船坞", "茶楼二楼", "城北厂房", "报社走廊"]


def build_chapter(no: int, title: str, beats: list[str], chars_per_chapter: int) -> str:
    names = list(CHARACTERS)
    parts = [f"第{no}章 {title}", ""]
    # 场景开头
    parts.append(f"{SCENES[no % len(SCENES)]}。{CHARACTERS[names[no % len(names)]].split('，')[0]}到的时候，"
                 f"{PLACES[no % len(PLACES)]}已经安静下来。")
    parts.append("")
    i = 0
    while sum(len(p) for p in parts) < chars_per_chapter:
        beat = beats[i % len(beats)]
        who = names[(no + i) % len(names)]
        who2 = names[(no + i + 2) % len(names)]
        sentence = TEMPLATES[i % len(TEMPLATES)].format(
            who=who,
            who2=who2,
            place=PLACES[(no + i) % len(PLACES)],
            scene=SCENES[(no + i) % len(SCENES)],
            line=LINES[(no + i) % len(LINES)],
            obj=OBJECTS[(no + i) % len(OBJECTS)],
        )
        # 把 beat 展开成叙述句，保证事实可被检索到
        parts.append(f"{beat}。{sentence}")
        parts.append("")
        if i % 3 == 2:
            parts.append(
                f"{who}把这一段记在本子上：{beat}，时间是{9 + i % 12}点{(i * 7) % 60:02d}分。"
                f"他抬头看了一眼{who2}，{who2}没有回应。"
            )
            parts.append("")
        i += 1
        if i > 200:
            break
    return "\n".join(parts).strip() + "\n\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chapters", type=int, default=24)
    ap.add_argument("--chars", type=int, default=1500, help="每章大致字数")
    ap.add_argument("--out", default="长夜将明.txt")
    ap.add_argument("--encoding", default="utf-8", choices=["utf-8", "gb18030"])
    args = ap.parse_args()

    chunks: list[str] = ["长夜将明", "", "作者：佚名", "", "内容简介：", "十年前的失踪案重新浮出水面，一名记者、一名法医和一名刑警，"
                        "沿着一条断掉的绳子，走回那个雨夜。", ""]
    for i in range(args.chapters):
        title, beats = BEATS[i % len(BEATS)]
        chunks.append(build_chapter(i + 1, title, beats, args.chars))

    out = Path(__file__).parent / args.out
    out.write_text("\n".join(chunks), encoding=args.encoding)
    total = sum(len(c) for c in chunks)
    print(f"wrote {out} chapters={args.chapters} chars≈{total} encoding={args.encoding}")


if __name__ == "__main__":
    main()
